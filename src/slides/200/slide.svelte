<h2>Every slide is the same shape</h2>

<div class="row">
  <p>
    A title, then one block that takes the rest of the page. There is nothing
    else to place, and no spacing to decide.
  </p>

  <ul>
    <li>
      The title reserves two lines whether it needs them or not, so it sits on
      the same baseline on every slide and the deck does not jump as it
      advances.
    </li>
    <li>
      The block below it fills whatever the title leaves, so a table or a
      diagram uses the page instead of floating in the top half of it.
    </li>
    <li>
      Sizes are pixels on a fixed stage, which Reveal scales to whatever it is
      projected onto, so a pixel is a fraction of the wall rather than of a
      screen.
    </li>
    <li>
      Four sizes exist and no more: the deck title, a slide title, content, and
      the small type that labels content.
    </li>
  </ul>
</div>
