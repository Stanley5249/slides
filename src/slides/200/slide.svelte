<h2>Every slide is the same shape</h2>

<p class="lede">
  An act label, a title, then rows. A slide never places its own spacing.
</p>

<ul>
  <li>
    The title reserves two lines whether it needs them or not, so it sits on the
    same baseline on every slide and the deck does not jump as it advances.
  </li>
  <li>
    Margins live on the elements, the way a document does it. Author order
    decides the gap.
  </li>
  <li>
    Sizes are pixels on a fixed stage, which Reveal scales to whatever it is
    projected onto, so a pixel is a fraction of the wall rather than of a
    screen.
  </li>
</ul>
