<h2>One clear idea deserves the whole slide</h2>

<div class="row">
  <p>
    Every slide has a title and one content area. The shared structure removes
    layout decisions and gives the audience a stable reading order.
  </p>

  <ul>
    <li>The title stays at the top and takes only the height it needs.</li>
    <li>The content fills the remaining stage instead of floating above it.</li>
    <li>Reveal scales the fixed stage to match the projector.</li>
    <li>Four text sizes cover titles, content, and supporting labels.</li>
  </ul>
</div>
