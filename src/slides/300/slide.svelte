<h2>Projection turns typography into accessibility</h2>

<div class="row">
  <p>
    <strong>Atkinson Hyperlegible</strong> keeps body text distinct when a projector
    lowers contrast. Short lines also reduce the distance the eye must track across
    the wall.
  </p>

  <p>
    Visual roles stay consistent: <em>emphasis</em> changes weight, a
    <a href="https://animotion.pages.dev/docs">link</a> uses the accent, and an
    identifier such as <code>--deck-ink</code> remains plain text.
  </p>

  <p>
    Color supports a claim already present in the words. One accent should keep
    one meaning throughout the deck.
  </p>
</div>
